const preferenceKey = "liushanmen.language";
let activeLanguage = "zh-CN";
try {
  if (localStorage.getItem(preferenceKey) === "en") activeLanguage = "en";
} catch { /* Storage can be unavailable without affecting language selection. */ }

export function language() {
  return activeLanguage;
}

export function setLanguage(value) {
  activeLanguage = value === "en" ? "en" : "zh-CN";
  try { localStorage.setItem(preferenceKey, activeLanguage); }
  catch { /* Keep the preferred language for the current page. */ }
}

export function t(message, values) {
  const translated = activeLanguage === "en" && Object.hasOwn(english, message) ? english[message] : message;
  return values ? translated.replace(/\{(\w+)\}/g, (match, key) => values[key] ?? match) : translated;
}

export function updateChrome() {
  document.documentElement.lang = activeLanguage;
  document.title = t("六扇门 · 情报工作台");
  document.querySelector('meta[name="description"]').content = t("六扇门是一款由用户定义任务的情报研判工作台。");
  for (const node of document.querySelectorAll("[data-i18n]")) node.textContent = t(node.dataset.i18n);
  for (const node of document.querySelectorAll("[data-i18n-label]")) node.setAttribute("aria-label", t(node.dataset.i18nLabel));
  for (const select of document.querySelectorAll(".language-select")) select.value = activeLanguage;
}
